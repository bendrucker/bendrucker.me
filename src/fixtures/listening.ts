/** Albums and podcasts, newest first. */
export async function loadListening(): Promise<ListeningItem[]> {
  const items = z.array(ListeningItemSchema).parse(LISTENING);
  return items.toSorted((a, b) => b.day.localeCompare(a.day));
}
